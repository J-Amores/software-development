#!/usr/bin/env bash
# Nothing may work locally that would break on Aurora DSQL (ADR 0003, ADR 0007):
# no sequences, triggers or stored procedures, exactly one DDL statement per
# migration, and no migration that mixes DDL with DML.
set -euo pipefail

migrations=${1:-tuition-reimbursement-app/backend/src/main/resources/db/migration}
offences=0
found=0

complain() {
  offences=$((offences + 1))
  echo "✗ $1: $2"
}

for file in "$migrations"/*.sql; do
  [ -e "$file" ] || continue
  found=$((found + 1))

  # Comments and string literals are not statements; strip line comments first.
  body=$(sed 's/--.*$//' "$file")

  for unsupported in "create sequence" "nextval" "create trigger" "create or replace trigger" \
                     "create procedure" "create or replace procedure" "create function" \
                     "create or replace function" "generated by default as identity" \
                     "generated always as identity" "serial" "bigserial"; do
    if printf '%s' "$body" | tr '[:upper:]' '[:lower:]' | grep -q -- "$unsupported"; then
      complain "$file" "uses \"$unsupported\", which Aurora DSQL does not support"
    fi
  done

  statements=$(printf '%s' "$body" | tr -d '\n' | tr ';' '\n' | grep -c '[^[:space:]]' || true)
  if [ "$statements" -ne 1 ]; then
    complain "$file" "holds $statements statements; Aurora DSQL allows one DDL statement per transaction, and Flyway runs each file in one"
  fi

  for dml in "insert into" "update " "delete from" "merge into"; do
    if printf '%s' "$body" | tr '[:upper:]' '[:lower:]' | grep -q -- "$dml"; then
      complain "$file" "mixes DDL with DML (\"$dml\"), which Aurora DSQL refuses in one transaction"
    fi
  done
done

echo "Checked $found migration(s) in $migrations."
[ "$offences" -eq 0 ] || exit 1
echo "Every migration stays inside the SQL Aurora DSQL supports."
